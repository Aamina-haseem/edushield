import { useQuery } from '@tanstack/react-query';
import { motion } from 'framer-motion';
import { CalendarClock, ShieldCheck } from 'lucide-react';
import { PageHeader, Pill, SectionTitle, Stat } from '@/components/common/Page';
import { Card } from '@/components/ui/Card';
import { useAuth } from '@/features/auth/context/AuthContext';
import { getMeDashboard } from '@/services/dashboard';
import type { RiskTier } from '@/types/contract';

const riskTone: Record<RiskTier, 'red' | 'amber' | 'green'> = { HIGH: 'red', MEDIUM: 'amber', LOW: 'green' };

export function StudentDashboardPage() {
  const { user } = useAuth();
  const { data, isLoading, isError } = useQuery({ queryKey: ['me-dashboard'], queryFn: getMeDashboard });

  if (isLoading) {
    return <div className="grid min-h-[50vh] place-items-center text-slate-500 dark:text-slate-400">Loading your dashboard…</div>;
  }

  if (isError || !data) {
    return <div className="grid min-h-[50vh] place-items-center text-slate-500 dark:text-slate-400">Unable to load your dashboard right now.</div>;
  }

  const { student, latestPrediction, interventions, notifications } = data;

  return (
    <div className="space-y-7">
      <PageHeader
        eyebrow="Your success workspace"
        title={`Welcome back, ${user?.name?.split(' ')[0] ?? student.name}`}
        description="Your own academic risk overview, generated by EduShield AI. Visible to you and to authorised advisors and administrators."
      />

      <section className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        <Stat label="Programme" value={student.programme} note={`Year ${student.yearOfStudy}`} />
        <Stat label="Final grade (G3)" value={student.features.g3 === null ? 'Not yet known' : `${student.features.g3}/20`} note={`G1 ${student.features.g1} · G2 ${student.features.g2}`} />
        <Stat label="Absences" value={String(student.features.absences)} note="Recorded absences" />
        <Stat label="Past failures" value={String(student.features.failures)} note="Modules previously failed" />
      </section>

      {latestPrediction ? (
        <Card className="p-6">
          <div className="flex flex-wrap items-center justify-between gap-4">
            <SectionTitle title="Your current risk assessment" description={`Model ${latestPrediction.modelVersion} · ${new Date(latestPrediction.predictedAt).toLocaleString()}`} />
            <Pill tone={riskTone[latestPrediction.riskTier]}>{latestPrediction.riskTier} risk · {latestPrediction.riskScore}%</Pill>
          </div>

          <div className="mt-5 grid gap-3 sm:grid-cols-2">
            {latestPrediction.shapFactors.slice(0, 6).map((factor) => (
              <motion.div
                key={factor.rawFeature}
                initial={{ opacity: 0, y: 8 }}
                animate={{ opacity: 1, y: 0 }}
                className="rounded-2xl border border-slate-200 p-4 dark:border-slate-800"
              >
                <div className="flex items-center justify-between gap-2">
                  <p className="text-sm font-bold">{factor.feature}</p>
                  <span
                    className={`shrink-0 text-xs font-bold ${factor.direction === 'increases' ? 'text-red-600 dark:text-red-300' : 'text-emerald-600 dark:text-emerald-300'}`}
                    title="This factor's share of the explanation, not a change in risk"
                  >
                    {factor.direction === 'increases' ? '↑ Raises' : '↓ Lowers'} · {factor.contributionPct.toFixed(0)}%
                  </span>
                </div>
                <p className="mt-1 text-xs text-slate-500 dark:text-slate-400">{factor.explanation}</p>
              </motion.div>
            ))}
            <p className="text-xs text-slate-500 sm:col-span-2 dark:text-slate-400">
              Percentages show each factor's share of this explanation, not a change in your risk score. They describe what the model associates with risk, not proven causes.
            </p>
          </div>
        </Card>
      ) : (
        <Card className="p-6 text-sm text-slate-500 dark:text-slate-400">
          No risk assessment has been run for you yet — check back after your advisor's next review cycle.
        </Card>
      )}

      <Card className="p-6">
        <SectionTitle title="Your support plan" description="Recommended actions from your advisor team" />
        {interventions.length === 0 ? (
          <p className="mt-4 text-sm text-slate-500 dark:text-slate-400">No active support plan right now — that's a good sign.</p>
        ) : (
          <div className="mt-4 space-y-3">
            {interventions.map((intervention) => (
              <div key={intervention.id} className="rounded-2xl border border-slate-200 p-4 dark:border-slate-800">
                <div className="flex items-center justify-between gap-3">
                  <Pill tone={riskTone[intervention.tier]}>{intervention.tier} risk</Pill>
                  <span className="text-xs font-semibold uppercase tracking-wide text-slate-400">{intervention.status.replace('_', ' ')}</span>
                </div>
                <ul className="mt-3 list-inside list-disc space-y-1 text-sm text-slate-600 dark:text-slate-300">
                  {intervention.recommendedActions.map((action) => <li key={action}>{action}</li>)}
                </ul>
                {intervention.nextMeetingAt && (
                  <p className="mt-3 flex items-center gap-2 text-xs text-slate-500 dark:text-slate-400">
                    <CalendarClock size={14} /> Next check-in: {new Date(intervention.nextMeetingAt).toLocaleString()}
                  </p>
                )}
              </div>
            ))}
          </div>
        )}
      </Card>

      <Card className="p-6">
        <SectionTitle title="Notifications" />
        {notifications.length === 0 ? (
          <p className="mt-4 text-sm text-slate-500 dark:text-slate-400">You're all caught up.</p>
        ) : (
          <ul className="mt-4 space-y-3">
            {notifications.map((notification) => (
              <li key={notification.id} className="flex items-start gap-3 text-sm">
                <ShieldCheck size={16} className="mt-0.5 shrink-0 text-sky-600 dark:text-sky-300" />
                <div>
                  <p className="font-semibold">{notification.title}</p>
                  <p className="text-slate-500 dark:text-slate-400">{notification.message}</p>
                </div>
              </li>
            ))}
          </ul>
        )}
      </Card>
    </div>
  );
}
