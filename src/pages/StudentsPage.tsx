import { useMemo } from 'react';
import { useNavigate, useSearchParams } from 'react-router-dom';
import { useQuery } from '@tanstack/react-query';
import { Filter, Search, UserPlus } from 'lucide-react';
import { Button } from '@/components/ui/Button';
import { Card } from '@/components/ui/Card';
import { PageHeader, Pill, SectionTitle, Stat } from '@/components/common/Page';
import { useAuth } from '@/features/auth/context/AuthContext';
import { listStudents } from '@/services/students';
import { listLatestPredictions } from '@/services/predictions';
import type { RiskTier } from '@/types/contract';

const riskTone: Record<RiskTier, 'red' | 'amber' | 'green'> = { HIGH: 'red', MEDIUM: 'amber', LOW: 'green' };
type RiskFilter = 'All' | RiskTier | 'UNASSESSED';
const RISK_FILTERS: { value: RiskFilter; label: string }[] = [
  { value: 'All', label: 'All' },
  { value: 'HIGH', label: 'High' },
  { value: 'MEDIUM', label: 'Medium' },
  { value: 'LOW', label: 'Low' },
  { value: 'UNASSESSED', label: 'Not assessed' },
];

const isRiskFilter = (value: string | null): value is RiskFilter => RISK_FILTERS.some((f) => f.value === value);

export function StudentsPage() {
  const navigate = useNavigate();
  const { user } = useAuth();
  // Search text and risk filter live in the URL, so the top-bar search and dashboard links
  // (e.g. /students?risk=HIGH) land on a pre-filtered list, and filters survive a reload.
  const [params, setParams] = useSearchParams();
  const q = params.get('q') ?? '';
  const riskParam = params.get('risk');
  const riskFilter: RiskFilter = isRiskFilter(riskParam) ? riskParam : 'All';
  const updateParams = (next: { q?: string; risk?: RiskFilter }) => {
    const merged = { q, risk: riskFilter, ...next };
    const entries: Record<string, string> = {};
    if (merged.q) entries.q = merged.q;
    if (merged.risk !== 'All') entries.risk = merged.risk;
    setParams(entries, { replace: true });
  };
  const setQ = (value: string) => updateParams({ q: value });
  const setRiskFilter = (value: RiskFilter) => updateParams({ risk: value });

  const studentsQuery = useQuery({ queryKey: ['students'], queryFn: () => listStudents() });
  const predictionsQuery = useQuery({ queryKey: ['latest-predictions'], queryFn: () => listLatestPredictions(2000) });

  const riskByStudentId = useMemo(() => {
    const map = new Map<string, { riskTier: RiskTier; riskScore: number }>();
    for (const prediction of predictionsQuery.data ?? []) {
      map.set(prediction.studentId, { riskTier: prediction.riskTier, riskScore: prediction.riskScore });
    }
    return map;
  }, [predictionsQuery.data]);

  const students = useMemo(() => studentsQuery.data ?? [], [studentsQuery.data]);
  const filtered = useMemo(
    () =>
      students.filter((s) => {
        const matchesSearch = `${s.name} ${s.studentNumber} ${s.programme}`.toLowerCase().includes(q.toLowerCase());
        const risk = riskByStudentId.get(s.id);
        const matchesRisk =
          riskFilter === 'All' ||
          (riskFilter === 'UNASSESSED' ? !risk : risk?.riskTier === riskFilter);
        return matchesSearch && matchesRisk;
      }),
    [students, q, riskFilter, riskByStudentId],
  );

  const totalStudents = students.length;
  const highRiskCount = [...riskByStudentId.values()].filter((r) => r.riskTier === 'HIGH').length;
  const attendanceAlerts = students.filter((s) => s.features.absences >= 13).length;
  const assessedCount = riskByStudentId.size;

  return (
    <div className="space-y-7">
      <PageHeader
        eyebrow="Student intelligence"
        title="Student Management"
        description="Search, segment and review student records with risk context generated by EduShield AI."
        actions={user?.role === 'admin' ? <Button icon={<UserPlus size={16} />} onClick={() => navigate('/students/new')}>Add student</Button> : undefined}
      />

      <section className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        <Stat label="Total students" value={String(totalStudents)} note="Loaded from the UCI dataset" />
        <Stat label="High risk" value={String(highRiskCount)} note="From latest predictions on record" />
        <Stat label="Absence alerts" value={String(attendanceAlerts)} note="Students with 13 or more absences" />
        <Stat label="Assessed" value={String(assessedCount)} note="Students with a prediction on record" />
      </section>

      <Card className="p-5">
        <div className="flex flex-col gap-4 lg:flex-row lg:items-center lg:justify-between">
          <SectionTitle title="Student directory" description={`${filtered.length} visible records`} />
          <label className="flex min-w-[280px] items-center gap-2 rounded-2xl border border-slate-200 px-3 py-2 dark:border-slate-700">
            <Search size={17} />
            <input
              value={q}
              onChange={(e) => setQ(e.target.value)}
              className="w-full bg-transparent text-sm outline-none"
              placeholder="Search student, ID or programme"
            />
          </label>
        </div>

        <div className="mt-3 flex items-center gap-2 overflow-x-auto pb-1">
          <Filter className="size-4 shrink-0 text-slate-400" />
          {RISK_FILTERS.map(({ value, label }) => (
            <button
              key={value}
              type="button"
              onClick={() => setRiskFilter(value)}
              className={`rounded-full px-3 py-1.5 text-xs font-bold transition ${riskFilter === value ? 'bg-[#003152] text-white' : 'bg-slate-100 text-slate-600 hover:bg-slate-200 dark:bg-slate-800 dark:text-slate-300'}`}
            >
              {label}
            </button>
          ))}
        </div>

        <div className="mt-5 overflow-x-auto">
          <table className="w-full min-w-[900px] text-left text-sm">
            <thead>
              <tr className="border-b border-slate-200 text-xs uppercase tracking-wider text-slate-500 dark:border-slate-800">
                <th className="px-3 py-3">Student</th>
                <th>Programme</th>
                <th>Year</th>
                <th>Absences</th>
                <th>Grade (G3)</th>
                <th>Risk</th>
                <th></th>
              </tr>
            </thead>
            <tbody>
              {studentsQuery.isLoading && (
                <tr><td className="px-3 py-6 text-slate-500 dark:text-slate-400" colSpan={7}>Loading students…</td></tr>
              )}
              {filtered.map((s) => {
                const risk = riskByStudentId.get(s.id);
                return (
                  <tr key={s.id} className="border-b border-slate-100 transition hover:bg-slate-50/80 dark:border-slate-800 dark:hover:bg-slate-800/50">
                    <td className="px-3 py-4">
                      <div className="font-bold">{s.name}</div>
                      <div className="text-xs text-slate-500">{s.studentNumber}</div>
                    </td>
                    <td>{s.programme}</td>
                    <td>Year {s.yearOfStudy}</td>
                    <td><span className={s.features.absences >= 13 ? 'font-bold text-red-600' : ''}>{s.features.absences}</span></td>
                    <td>{s.features.g3 === null ? '—' : `${s.features.g3}/20`}</td>
                    <td>{risk ? <Pill tone={riskTone[risk.riskTier]}>{risk.riskTier} · {risk.riskScore}%</Pill> : <Pill tone="slate">Not assessed</Pill>}</td>
                    <td>
                      <button className="font-bold text-sky-700 dark:text-sky-300" onClick={() => navigate(`/students/${s.id}`)}>View</button>
                    </td>
                  </tr>
                );
              })}
              {!studentsQuery.isLoading && filtered.length === 0 && (
                <tr><td className="px-3 py-6 text-slate-500 dark:text-slate-400" colSpan={7}>No students match this search.</td></tr>
              )}
            </tbody>
          </table>
        </div>
      </Card>
    </div>
  );
}
